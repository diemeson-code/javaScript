let fruta = "maçã";

switch (fruta) {
  case "banana":
    console.log("Eu gosto de bananas!");
    break;

  case "maçã":
    console.log("As maçãs são deliciosas!");
    break;

  default:
    console.log("Eu gosto de todas as frutas!");
}
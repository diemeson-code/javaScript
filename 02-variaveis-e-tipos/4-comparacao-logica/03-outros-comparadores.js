/*
Outros operadores de comparação são o Maior que ( > ), o Menor que ( < ) e o Maior ou Igual que ( >= ) 
e o Menor ou Igual que ( <= ).

Por exemplo:
*/

var a = 10;
var b = 20;

if (a > b) {
  console.log("A variável a é maior que a variável b!");
} else {
  console.log("A variável a não é maior que a variável b!");
}
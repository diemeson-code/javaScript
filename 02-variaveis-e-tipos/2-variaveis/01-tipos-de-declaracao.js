/*
No JavaScript, existem três maneiras principais de declarar uma variável: var, let e const.
Cada um tem suas próprias características e usos:

var: Esta é a maneira mais antiga de declarar variáveis em JavaScript. As variáveis declaradas
com var são funcionalmente de escopo global ou de escopo de função.
*/
var x = 10;

/*
let: Introduzido no ECMAScript 6 (ES6), let permite declarar variáveis limitadas ao escopo do bloco,
instrução ou expressão onde são usadas, diferentemente de var.
*/
let y = 20;

/*
const: Também introduzido no ES6, const é semelhante a let em termos de escopo de bloco. No entanto, 
const é usada para declarar constantes, ou variáveis cujos valores não podem ser alterados após a 
atribuição inicial.
*/
const z = 30;